"""Generates the files derived from the row model and the layout, and checks the committed ones.

The schema comes from the row model. The repeatable migration holds the check on `kind` and the
producer-nullness check of each addressing class, so a kind added to the layout needs no hand edit.

Usage: python -m wdf_artifactindex.gen [--check] [--root DIR]
"""

import argparse
import json
import sys
from pathlib import Path

import yaml

from .models import ArtifactRow, ArtifactUse

REPO_ROOT = Path(__file__).resolve().parents[4]
SCHEMAS = {
    Path("contracts/state/schemas/artifact-row/2.json"): (ArtifactRow, "artifact-row", 2),
    Path("contracts/state/schemas/artifact-use/1.json"): (ArtifactUse, "artifact-use", 1),
}
LAYOUT = Path("contracts/artifact/layout.yaml")
KINDS_SQL = Path("packages/artifactindex/src/wdf_artifactindex/migrations/R__artifact_kinds.sql")

CACHE_KIND = "compile-cache"
PRODUCER = ("producer_job", "producer_task", "producer_attempt")


def render(model: type = ArtifactRow, name: str = "artifact-row", version: int = 2) -> str:
    schema = model.model_json_schema()
    schema["$schema"] = "https://json-schema.org/draft/2020-12/schema"
    schema["$id"] = f"urn:wdf:schema:state.{name}:{version}"
    schema["title"] = f"{name} {version}"
    return json.dumps(schema, indent=2, sort_keys=True, ensure_ascii=False) + "\n"


def _in(kinds: list[str]) -> str:
    return "kind IN (" + ", ".join(f"'{k}'" for k in kinds) + ")" if kinds else "false"


def render_kinds(layout: dict) -> str:
    kinds = layout["kinds"]
    by_class = {
        c: [k for k, spec in kinds.items() if spec["class"] == c]
        for c in ("content-addressed", "attempt-scoped")
    }
    every = [*kinds, CACHE_KIND]
    null = " AND ".join(f"{c} IS NULL" for c in PRODUCER)
    set_ = " AND ".join(f"{c} IS NOT NULL" for c in PRODUCER)
    return f"""\
-- Generated by python -m wdf_artifactindex.gen from the artifact layout, never edited by hand.
-- Re-applied when the layout changes, so each constraint is replaced and validated again.
ALTER TABLE artifact DROP CONSTRAINT IF EXISTS artifact_kind_known;
ALTER TABLE artifact ADD CONSTRAINT artifact_kind_known CHECK ({_in(every)}) NOT VALID;
ALTER TABLE artifact VALIDATE CONSTRAINT artifact_kind_known;

-- A content-addressed kind has no producer and an attempt-scoped kind has one.
-- A cache entry is held by the table definition and is outside this check.
ALTER TABLE artifact DROP CONSTRAINT IF EXISTS artifact_producer_by_class;
ALTER TABLE artifact ADD CONSTRAINT artifact_producer_by_class CHECK (
    kind = '{CACHE_KIND}'
    OR ({_in(by_class["content-addressed"])} AND {null})
    OR ({_in(by_class["attempt-scoped"])} AND {set_})
) NOT VALID;
ALTER TABLE artifact VALIDATE CONSTRAINT artifact_producer_by_class;
"""


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="wdf_artifactindex.gen")
    parser.add_argument(
        "--check", action="store_true", help="fail when a committed generated file differs"
    )
    parser.add_argument("--root", type=Path, default=REPO_ROOT)
    args = parser.parse_args(argv)

    layout = yaml.safe_load((args.root / LAYOUT).read_text())
    files = {path: render(*spec) for path, spec in SCHEMAS.items()}
    files[KINDS_SQL] = render_kinds(layout)
    drifted = []
    for relative, text in files.items():
        path = args.root / relative
        if not args.check:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
        elif not path.is_file() or path.read_text() != text:
            drifted.append(relative)
    for relative in drifted:
        print(f"drift: {relative}", file=sys.stderr)
    return 1 if drifted else 0


if __name__ == "__main__":
    sys.exit(main())
