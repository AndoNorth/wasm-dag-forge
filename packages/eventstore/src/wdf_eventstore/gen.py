"""Generates the event row schema, the retention schema and the event policy migration.

The policy migration is read from contracts/state/retention.yaml, so a moved window is one
regeneration away. `--check` fails when a committed file differs.

Usage: python -m wdf_eventstore.gen [--check] [--root DIR]
"""

import argparse
import json
import sys
from pathlib import Path

import yaml

from .models import EventRow, Retention
from .retention import EVENT_TABLE, Refused, check

REPO_ROOT = Path(__file__).resolve().parents[4]
RETENTION = Path("contracts/state/retention.yaml")
POLICIES = Path("packages/eventstore/src/wdf_eventstore/migrations/R__event_policies.sql")
OUTPUTS = {
    Path("contracts/state/schemas/event-row/1.json"): (
        EventRow,
        "urn:wdf:schema:state.event-row:1",
    ),
    Path("contracts/state/retention.schema.json"): (Retention, "urn:wdf:schema:state.retention:1"),
}


def render(model, schema_id: str) -> str:
    schema = model.model_json_schema()
    schema["$schema"] = "https://json-schema.org/draft/2020-12/schema"
    schema["$id"] = schema_id
    return json.dumps(schema, indent=2, sort_keys=True, ensure_ascii=False) + "\n"


def render_policies(retention: Retention) -> str:
    """Each policy is removed and added again, because adding an existing one keeps its interval."""
    compress = retention.housekeeping[EVENT_TABLE].compress_after_days
    drop = retention.windows[EVENT_TABLE].drop_after_days
    lines = [
        "-- Generated by python -m wdf_eventstore.gen from contracts/state/retention.yaml.",
        "-- Do not edit.",
        f"SELECT remove_compression_policy('{EVENT_TABLE}', if_exists => true);",
        f"SELECT add_compression_policy('{EVENT_TABLE}',"
        f" compress_after => INTERVAL '{compress} days');",
        f"SELECT remove_retention_policy('{EVENT_TABLE}', if_exists => true);",
        f"SELECT add_retention_policy('{EVENT_TABLE}', drop_after => INTERVAL '{drop} days');",
    ]
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="wdf_eventstore.gen")
    parser.add_argument("--check", action="store_true", help="fail when a committed file differs")
    parser.add_argument("--root", type=Path, default=REPO_ROOT)
    args = parser.parse_args(argv)

    outputs = {path: render(model, schema_id) for path, (model, schema_id) in OUTPUTS.items()}
    retention_file = args.root / RETENTION
    if retention_file.is_file():
        retention = Retention.model_validate(yaml.safe_load(retention_file.read_text()))
        try:
            check(retention)
        except Refused as refused:
            print(f"reason: {refused}", file=sys.stderr)
            return 1
        outputs[POLICIES] = render_policies(retention)
    elif not args.check:
        print(f"missing: {RETENTION}", file=sys.stderr)
        return 1

    drift = []
    for relative, text in outputs.items():
        path = args.root / relative
        if not args.check:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
        elif not path.is_file() or path.read_text() != text:
            drift.append(relative)
    if args.check and not retention_file.is_file():
        drift.append(POLICIES)
    for relative in drift:
        print(f"drift: {relative}", file=sys.stderr)
    return 1 if drift else 0


if __name__ == "__main__":
    sys.exit(main())
