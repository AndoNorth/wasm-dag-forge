"""Generates the job-row schema from the row model and the vocabulary migration from the contracts.

The migration `R__job_vocab.sql` holds the status tables, the checks on `status` and `job_class`
and the transition guard, read from contracts/status/status.yaml and contracts/job/limits.yaml.

Usage: python -m wdf_jobstate.gen [--check] [--root DIR]
"""

import argparse
import json
import sys
from pathlib import Path

import yaml

from .models import JobRow

REPO_ROOT = Path(__file__).resolve().parents[4]
SCHEMA = Path("contracts/state/schemas/job-row/1.json")
VOCAB = Path("packages/jobstate/src/wdf_jobstate/migrations/R__job_vocab.sql")
STATUS = Path("contracts/status/status.yaml")
LIMITS = Path("contracts/job/limits.yaml")

HEADER = """\
-- Generated by python -m wdf_jobstate.gen from contracts/status/status.yaml
-- and contracts/job/limits.yaml.
-- Repeatable: it replaces what it owns, so it is applied again whenever a contract moves.
"""

TABLES = """\
CREATE TABLE IF NOT EXISTS job_status (
    status text PRIMARY KEY,
    terminal boolean NOT NULL
);

CREATE TABLE IF NOT EXISTS job_transition (
    from_status text NOT NULL REFERENCES job_status (status),
    to_status text NOT NULL REFERENCES job_status (status),
    row_only boolean NOT NULL,
    PRIMARY KEY (from_status, to_status)
);

DELETE FROM job_transition;
DELETE FROM job_status;
"""

GUARD = """\
CREATE OR REPLACE FUNCTION accepted_job_guard_status() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM job_transition WHERE from_status = OLD.status AND to_status = NEW.status
    ) THEN
        RAISE EXCEPTION 'status move % to % is not in job_transition', OLD.status, NEW.status
            USING ERRCODE = 'check_violation';
    END IF;
    RETURN NEW;
END
$$;

DROP TRIGGER IF EXISTS accepted_job_guard_status ON accepted_job;
CREATE TRIGGER accepted_job_guard_status BEFORE UPDATE OF status ON accepted_job
    FOR EACH ROW WHEN (OLD.status IS DISTINCT FROM NEW.status)
    EXECUTE FUNCTION accepted_job_guard_status();
"""


def _literal(value: str) -> str:
    return "'" + value.replace("'", "''") + "'"


def _bool(value: bool) -> str:
    return "true" if value else "false"


def _check(name: str, column: str, values: list[str]) -> str:
    members = ", ".join(_literal(v) for v in values)
    return (
        f"ALTER TABLE accepted_job DROP CONSTRAINT IF EXISTS {name};\n"
        f"ALTER TABLE accepted_job ADD CONSTRAINT {name}"
        f" CHECK ({column} IN ({members})) NOT VALID;\n"
        f"ALTER TABLE accepted_job VALIDATE CONSTRAINT {name};\n"
    )


def render_vocab(root: Path) -> str:
    status = yaml.safe_load((root / STATUS).read_text())
    classes = yaml.safe_load((root / LIMITS).read_text())["profiles"]["ci"]["classes"]
    terminal = set(status["terminal"])
    statuses = ",\n".join(
        f"    ({_literal(s)}, {_bool(s in terminal)})" for s in status["statuses"]
    )
    moves = ",\n".join(
        f"    ({_literal(t['from'])}, {_literal(t['to'])}, {_bool(t.get('row_only', False))})"
        for t in status["transitions"]
    )
    return "\n".join(
        [
            HEADER,
            TABLES,
            f"INSERT INTO job_status (status, terminal) VALUES\n{statuses};\n",
            f"INSERT INTO job_transition (from_status, to_status, row_only) VALUES\n{moves};\n",
            _check("accepted_job_status_known", "status", status["statuses"]),
            _check("accepted_job_class_known", "job_class", classes),
            GUARD,
        ]
    )


def render() -> str:
    schema = JobRow.model_json_schema()
    schema["$schema"] = "https://json-schema.org/draft/2020-12/schema"
    schema["$id"] = "urn:wdf:schema:state.job-row:1"
    schema["title"] = "job-row 1"
    return json.dumps(schema, indent=2, sort_keys=True, ensure_ascii=False) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="wdf_jobstate.gen")
    parser.add_argument(
        "--check", action="store_true", help="fail when a committed generated file differs"
    )
    parser.add_argument("--root", type=Path, default=REPO_ROOT)
    args = parser.parse_args(argv)

    drifted = False
    for name, text in {SCHEMA: render(), VOCAB: render_vocab(args.root)}.items():
        path = args.root / name
        if not args.check:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
        elif not path.is_file() or path.read_text() != text:
            print(f"drift: {name}", file=sys.stderr)
            drifted = True
    return 1 if drifted else 0


if __name__ == "__main__":
    sys.exit(main())
